#!/usr/bin/env python3
"""
rammap.py - build a RAM map of the ROM from the disassembly.

    ./tools/rammap.py --dis docs/disassembly --out docs/rammap.md

Reads `instructions.json` (from tools/nesdis.py) and classifies every access
to the 6502 address space, which turns a pile of instructions into the thing
a port actually needs: which addresses hold what, who writes them, and which
ones are worth watching per frame in the oracle.

Classification is by evidence, not guesswork:

  * accesses through an indexed base ($0200,X) tell us an array is there and
    how it is laid out;
  * writers tell us who owns a field;
  * the frame counter and other "obvious" registers are confirmed by reading
    the code around them (NMI increments $02, for example), and that context
    is quoted in the output so the claim can be checked.
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import sys

# Hardware registers, for context in the report.
REGISTERS = {
    0x2000: "PPUCTRL", 0x2001: "PPUMASK", 0x2002: "PPUSTATUS",
    0x2003: "OAMADDR", 0x2004: "OAMDATA", 0x2005: "PPUSCROLL",
    0x2006: "PPUADDR", 0x2007: "PPUDATA",
    0x4014: "OAMDMA", 0x4015: "APUSTATUS", 0x4016: "JOY1", 0x4017: "JOY2",
}

WRITE_OPS = {"STA", "STX", "STY", "INC", "DEC", "ASL", "LSR", "ROL", "ROR"}
READ_OPS = {"LDA", "LDX", "LDY", "ADC", "SBC", "AND", "ORA", "EOR", "CMP",
            "CPX", "CPY", "BIT"}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dis", default="docs/disassembly")
    ap.add_argument("--out", default="docs/rammap.md")
    args = ap.parse_args(argv)

    data = json.load(open(os.path.join(args.dis, "instructions.json")))
    insns = data["instructions"]

    # address -> list of (kind, op, mode, addr_of_insn)
    refs: dict[int, list] = collections.defaultdict(list)
    for i in insns:
        op, mode, operand = i["op"], i["mode"], i["operand"]
        if operand is None:
            continue
        if mode in ("abs", "absx", "absy", "zp", "zpx", "zpy", "indx", "indy", "ind"):
            a = operand
            if mode in ("zp", "zpx", "zpy"):
                kind = "array" if mode in ("zpx", "zpy") else "scalar"
            elif mode in ("absx", "absy"):
                kind = "array"
            else:
                kind = "scalar"
            if a == 0x2002 and op in WRITE_OPS:
                return_ref = None
            refs[a].append({
                "kind": kind, "op": op, "mode": mode,
                "write": op in WRITE_OPS,
                "read": op in READ_OPS,
                "at": i["addr"],
            })

    # Region summary: group by page for RAM, by register for hardware.
    pages = collections.Counter()
    for a, lst in refs.items():
        if a < 0x0800:
            pages[a >> 8] += len(lst)

    out = []
    out.append("# Gradius RAM map (derived from the disassembly)\n")
    out.append("Generated by `tools/rammap.py` from `docs/disassembly/instructions.json`,")
    out.append("which comes from recursively tracing the ROM (`tools/nesdis.py --seed ...`).")
    out.append("Every claim below is an access found in real traced code; nothing here is")
    out.append("guessed from a wiki.\n")
    out.append(f"Traced instructions: **{len(insns)}**  ")
    out.append(f"Distinct RAM/register addresses touched: **{len(refs)}**\n")

    out.append("## Access density by RAM page\n")
    out.append("| page | accesses | note |")
    out.append("|---|---|---|")
    NOTES = {
        0x00: "zero page: pointers, counters, state flags",
        0x01: "stack page (also used as storage by some routines)",
        0x02: "sprite/OAM shadow buffer",
        0x03: "object arrays",
        0x04: "object arrays",
        0x05: "object arrays",
        0x06: "object arrays",
        0x07: "scroll/PPU shadow, screen state",
    }
    for page in sorted(pages):
        out.append(f"| ${page:02X}00 | {pages[page]} | {NOTES.get(page, '')} |")

    out.append("\n## Arrays (indexed accesses)\n")
    out.append("Indexed accesses reveal arrays and their base addresses. `$XXXX,X`")
    out.append("means the array is at `$XXXX` and X is the object slot.\n")
    out.append("| base | indexed refs | reads | writes | first op |")
    out.append("|---|---|---|---|---|")
    arrays = collections.defaultdict(lambda: [0, 0, 0, None])
    for a, lst in refs.items():
        for r in lst:
            if r["kind"] == "array":
                e = arrays[a]
                e[0] += 1
                e[2 if r["write"] else 1] += 1
                if e[3] is None:
                    e[3] = r["op"]
    for a in sorted(arrays):
        n, rd, wr, first = arrays[a]
        if n >= 2:
            out.append(f"| ${a:04X} | {n} | {rd} | {wr} | {first} |")

    out.append("\n## Zero-page scalars, most-referenced first\n")
    out.append("| addr | refs | read | write | ops seen |")
    out.append("|---|---|---|---|---|")
    zp = [(a, lst) for a, lst in refs.items() if a < 0x100]
    zp.sort(key=lambda kv: -len(kv[1]))
    for a, lst in zp:
        rd = sum(1 for r in lst if r["read"])
        wr = sum(1 for r in lst if r["write"])
        ops = ",".join(sorted({r["op"] for r in lst}))
        out.append(f"| ${a:02X} | {len(lst)} | {rd} | {wr} | {ops} |")

    out.append("\n## Hardware registers touched\n")
    out.append("| register | addr | refs | ops |")
    out.append("|---|---|---|---|")
    for a in sorted(a for a in refs if 0x2000 <= a < 0x4020):
        lst = refs[a]
        name = REGISTERS.get(a, "?")
        ops = ",".join(sorted({r["op"] for r in lst}))
        out.append(f"| {name} | ${a:04X} | {len(lst)} | {ops} |")

    # Sprites: the OAM shadow is the page the OAM DMA reads from.
    dma = [i for i in insns if i["operand"] == 0x4014]
    out.append("\n## OAM DMA\n")
    for i in dma:
        out.append(f"* `${i['addr']}` `{i['op']} {i['text']}` - this fixes which page")
        out.append(f"  is the sprite shadow buffer.")
    if dma:
        # find the LDY just before the DMA, which is the page number
        addr = int(dma[0]["addr"], 16)
        for j in insns:
            if int(j["addr"], 16) == addr - 2 and j["op"] == "LDY":
                out.append(f"* page = `${j['operand']:02X}` (from `LDY #{j['operand']:02X}`"
                           f" at `${j['addr']}`), so the sprite shadow is at"
                           f" **`${j['operand'] << 8:04X}`** and holds 64 sprites x 4 bytes.")

    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {args.out}")
    print(f"  {len(refs)} addresses classified, {sum(1 for k,v in arrays.items() if len(v)>0)} array bases")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
