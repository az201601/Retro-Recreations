#!/usr/bin/env python3
"""Deliverable 4: write the tables of work/news_data.pkl into the marked block at the end of
recreation/04_newscaster/gml/obj_intro_Create.gml. Each table is a string of fixed-width decimal numbers that the
Create event unpacks into an array (far shorter than one assignment per entry)."""
import os, pickle
from emu import WORK
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PATH = os.path.join(ROOT, 'recreation', '04_newscaster', 'gml', 'obj_intro_Create.gml')
A, B = '// >>> generated by tools/capture/gen_news_gml.py - do not edit by hand\n', '// <<< end of the generated tables\n'

def table(name, vals, comment, add=0):
    vals = [v + add for v in vals]; assert min(vals) >= 0, name
    w = len(str(max(vals))); s = ''.join('%0*d' % (w, v) for v in vals)
    per = (100 // w) * w
    parts = ['"%s"' % s[i:i + per] for i in range(0, len(s), per)]
    out = '// %s\ns = %s;\n' % (comment, '\n  + '.join(parts))
    out += 'for (i = %d; i >= 0; i -= 1) %s[i] = real(string_copy(s, i * %d + 1, %d))%s;\n' % (len(vals) - 1, name, w, w, ' - %d' % add if add else '')
    return out

def gen():
    D = pickle.load(open(os.path.join(WORK, 'news_data.pkl'), 'rb'))
    P = D['pages']; tk = [t for p in P for t in p['ticks']]; pc = [x for c in D['cels'] for x in c]; b = D['ball']; st = D['spin']
    assert D['names'] == ['chip', 'gadget', 'monty', 'zipper', 'dale', 'star'] and b['actor'] == 3 and st == dict(actor=5, parent=4, first=st['first'])
    assert min(y + dy for c, x, y in D['trk'] if c for dx, dy, _ in D['cels'][c - 1]) >= 0
    assert min(min(b['hy']) + dy for cc in (b['cel'], b['cel'] + 1, b['cel2'], b['cel2'] + 1) for dx, dy, _ in D['cels'][cc - 1]) >= 0
    o = 'var s;\n'
    o += 'nw_pages = %d;  nw_segs = %d;\n' % (len(P), len(D['segs']))
    o += 'nw_music_t0 = %d;     // nt on which the music starts\nnw_music_len = %d;   // length of the music loop in frames\n' % (D['m0'], D['loop'])
    o += 'nw_star_first = %d;   // frame of the star\'s track on which it becomes visible\n' % st['first']
    o += '// Zipper: frames of his entrance before he hovers, hover picture (cel + 1; +1 = wings down), picture of the last\n'
    o += '// 12 frames of the 252-frame cycle, hover x, page and delay after which he may leave, his exit in the track table\n'
    o += 'nw_ball_hover = %d;  nw_ball_cel = %d;  nw_ball_cel2 = %d;  nw_ball_x = %d;\n' % (b['hover'], b['cel'], b['cel2'], b['x'])
    o += 'nw_ball_rel_page = %d;  nw_ball_rel_off = %d;  nw_ball_first = %d;  nw_ball_count = %d;\n' % (b['rel_gap'], b['rel_off'], b['p0'], b['n'])
    o += table('nw_ball_hy', b['hy'], 'Zipper: y while hovering, 12-frame cycle')
    o += '// text box rows 3..8: delay of the row going blank when a page is cleared\n'
    o += ''.join('nw_clear_at[%d] = %d;  ' % (r, D['clear_at'][r]) for r in sorted(D['clear_at'], reverse=True)).rstrip() + '\n'
    first = []; n = 0
    for p in P: first.append(n); n += len(p['ticks'])
    o += table('nw_pg_pre', [p['pre'] for p in P], 'pages: frames between the previous page being cleared and the first typing step')
    o += table('nw_pg_speaker', [p['speaker'] for p in P], 'pages: actor whose mouth moves (-1 = nobody)', 1)
    o += table('nw_pg_voice', [p['voice'] for p in P], 'pages: typing sound (index of nw_type_snd)')
    o += table('nw_pg_first', first, 'pages: first typing step in the nw_tk_ tables')
    o += table('nw_pg_count', [len(p['ticks']) for p in P], 'pages: number of typing steps')
    o += table('nw_tk_kind', [t[0] for t in tk], 'typing steps: 0 = a character, 1 = a space, 2 = go to the next line')
    o += table('nw_tk_row', [t[1] for t in tk], 'typing steps: text box row')
    o += table('nw_tk_col', [t[2] for t in tk], 'typing steps: text box column')
    o += table('nw_tk_top', [t[3] for t in tk], 'typing steps: glyph + 1 (spr_news_font sub-image = glyph * 7 + brightness)')
    o += table('nw_tk_bot', [t[4] for t in tk], 'typing steps: glyph + 1 of the lower half in the row below, 0 = none')
    sg = D['segs']
    o += table('nw_sg_actor', [x['actor'] for x in sg], 'movements: actor')
    o += table('nw_sg_page', [x['gap'] for x in sg], 'movements: starts after the page before this one was cleared ...')
    o += table('nw_sg_off', [x['off'] for x in sg], 'movements: ... this many frames later')
    o += table('nw_sg_first', [x['p0'] for x in sg], 'movements: first frame in the nw_tr_ tables')
    o += table('nw_sg_count', [x['n'] for x in sg], 'movements: number of frames')
    o += table('nw_tr_cel', [x[0] for x in D['trk']], 'track frames: cel + 1, 0 = not shown')
    o += table('nw_tr_x', [x[1] for x in D['trk']], 'track frames: x', 128)
    o += table('nw_tr_y', [x[2] for x in D['trk']], 'track frames: y')
    first = []; n = 0
    for c in D['cels']: first.append(n); n += len(c)
    o += table('nw_cel_first', first, 'cels: first piece in the nw_pc_ tables')
    o += table('nw_cel_count', [len(c) for c in D['cels']], 'cels: number of 8x8 pieces')
    o += table('nw_open', D['open'], 'cels: [cel + 1] -> cel + 1 of the same pose with the mouth open, 0 = none')
    o += table('nw_pc_dx', [x[0] for x in pc], 'pieces: x offset from the actor position', 64)
    o += table('nw_pc_dy', [x[1] for x in pc], 'pieces: y offset', 64)
    o += table('nw_pc_img', [x[2] for x in pc], 'pieces: picture (spr_news_piece sub-image = picture * 7 + brightness)')
    o += table('nw_note', [1 if i in set(D['notes']) else 0 for i in range(D['loop'])], 'music loop frames on which a note of snd_news_music_b starts')
    s = open(PATH).read(); i = s.index(A) + len(A); j = s.index(B)
    open(PATH, 'w').write(s[:i] + o + s[j:])
    print('wrote %d lines of tables into %s' % (o.count('\n'), os.path.relpath(PATH, ROOT)))
if __name__ == '__main__': gen()
